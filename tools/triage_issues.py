#!/usr/bin/env python3
"""Beta feedback triage (T6): GitHub issues -> docs/acceptance/user-reports.md.

Reads the issues of CIPFZ/inkra (issue forms in .github/ISSUE_TEMPLATE), takes
the version, platform, package and the `graphics:` log line from each body,
flags reports that may block writing, and rewrites the generated section of
docs/acceptance/user-reports.md between the triage markers. Everything outside
the markers (the hand-written log of fixes) is left alone.

    python3 tools/triage_issues.py                 # GitHub API (GH_TOKEN / GITHUB_TOKEN if set)
    python3 tools/triage_issues.py --input issues.json   # a saved API response
    python3 tools/triage_issues.py --fetch-logs    # also read attached inkra.log files
    python3 tools/triage_issues.py --dry-run       # print the table, write nothing
    python3 tools/triage_issues.py --self-test

Anonymous API calls are limited to 60 per hour per IP address; set GH_TOKEN
(read-only, public repositories) where that is not enough.
"""

import json
import os
import re
import sys
import urllib.error
import urllib.request

REPO = "CIPFZ/inkra"
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REPORTS = os.path.join(ROOT, "docs", "acceptance", "user-reports.md")
START = "<!-- triage:start (generated by tools/triage_issues.py; edits here are overwritten) -->"
END = "<!-- triage:end -->"

# Issue form headings (`### <label>`) -> field. The labels are bilingual; a
# keyword of either language is enough, so small template edits keep working.
FIELDS = [
    ("version", ("version", "版本")),
    ("platform", ("platform", "平台")),
    ("package", ("package", "安装方式")),
    ("graphics", ("graphics", "graphics:")),
    ("area", ("area", "范围")),
    ("steps", ("steps", "重现步骤")),
    ("expected", ("expected", "期望")),
]

# Words that suggest the editor cannot be used for writing (iron rule 7 and
# the bug template): crashes, lost text, no typing, no saving, no start.
BLOCKING = re.compile(
    r"crash|panic|freez|hang|data loss|lost (my |the )?(text|work|content|changes)|"
    r"can(no|')t (type|save|open|start|launch)|won'?t (start|launch|open)|"
    r"崩溃|闪退|卡死|无响应|丢失|丢了|无法(输入|保存|打开|启动)|不能(输入|保存|打开|启动)|打不开|启动不了",
    re.IGNORECASE,
)
GRAPHICS = re.compile(r"graphics: backends[^\n`]*")
VERSION = re.compile(r"\b\d+\.\d+\.\d+(?:-[0-9A-Za-z.]+)?\b")


def field_of(heading):
    h = heading.lower()
    for key, words in FIELDS:
        if any(w in h for w in words):
            return key
    return None


def parse_body(body):
    """Fields of an issue-form body (`### Label` sections)."""
    out = {}
    body = (body or "").replace("\r\n", "\n")
    parts = re.split(r"^###\s+(.+?)\s*$", body, flags=re.MULTILINE)
    # parts: [before, heading1, text1, heading2, text2, ...]
    for heading, text in zip(parts[1::2], parts[2::2]):
        key = field_of(heading)
        value = text.strip()
        if key and value and value != "_No response_" and key not in out:
            out[key] = value
    m = GRAPHICS.search(out.get("graphics", "")) or GRAPHICS.search(body)
    if m:
        out["graphics"] = m.group(0).strip()
    elif "graphics" in out:
        out["graphics"] = out["graphics"].splitlines()[0].strip()[:200]
    if "version" in out:
        v = VERSION.search(out["version"])
        out["version"] = v.group(0) if v else out["version"].splitlines()[0][:40]
    return out


def attachments(body):
    """Links to attached log files."""
    return re.findall(r"https://github\.com/(?:user-attachments/files|[^)\s]+/files)/[^)\s]+", body or "")


def blocking(issue, fields):
    text = " ".join([issue.get("title", ""), fields.get("steps", ""), fields.get("expected", "")])
    return bool(BLOCKING.search(text))


def kind(issue):
    labels = {l["name"] if isinstance(l, dict) else l for l in issue.get("labels", [])}
    for k in ("bug", "rendering", "enhancement"):
        if k in labels:
            return k
    return "-"


def get(url, token):
    headers = {"Accept": "application/vnd.github+json", "User-Agent": "inkra-triage"}
    if token:
        headers["Authorization"] = f"Bearer {token}"
    with urllib.request.urlopen(urllib.request.Request(url, headers=headers), timeout=60) as r:
        return r.read()


def fetch_issues(token):
    out, page = [], 1
    while True:
        url = f"https://api.github.com/repos/{REPO}/issues?state=all&per_page=100&page={page}"
        batch = json.loads(get(url, token))
        out += [i for i in batch if "pull_request" not in i]
        if len(batch) < 100:
            return out
        page += 1


def cell(s, n=60):
    s = (s or "").replace("|", "\\|").replace("\n", " ").strip()
    return (s[: n - 1] + "…") if len(s) > n else (s or "—")


def rows(issues, token=None, fetch_logs=False):
    out = []
    for i in sorted(issues, key=lambda i: i["number"]):
        f = parse_body(i.get("body"))
        if fetch_logs and "graphics" not in f:
            for url in attachments(i.get("body")):
                try:
                    m = GRAPHICS.search(get(url, token).decode("utf-8", "replace"))
                except Exception as e:  # attachments may be gone or private
                    print(f"#{i['number']}: cannot read {url}: {e}", file=sys.stderr)
                    continue
                if m:
                    f["graphics"] = m.group(0).strip()
                    break
        out.append({
            "number": i["number"],
            "url": i.get("html_url", f"https://github.com/{REPO}/issues/{i['number']}"),
            "title": i.get("title", ""),
            "state": i.get("state", ""),
            "kind": kind(i),
            "blocking": kind(i) == "bug" and blocking(i, f),
            **{k: f.get(k, "") for k in ("version", "platform", "package", "graphics", "area")},
        })
    return out


def table(rs):
    lines = [
        "| Issue | 类型 | 状态 | 标题 | 版本 | 平台 | 安装方式 | graphics | 初判 |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rs:
        flag = "**可能阻塞写作**" if r["blocking"] else ""
        lines.append(
            f"| [#{r['number']}]({r['url']}) | {r['kind']} | {r['state']} | {cell(r['title'], 50)} | "
            f"{cell(r['version'], 20)} | {cell(r['platform'], 24)} | {cell(r['package'], 16)} | "
            f"{cell(r['graphics'], 90)} | {flag} |"
        )
    if not rs:
        lines.append("| — | — | — | 暂无 issue | — | — | — | — | — |")
    return "\n".join(lines)


def section(rs):
    by = lambda key: sorted({r[key] for r in rs if r[key]})
    summary = (
        f"共 {len(rs)} 个 issue（open {sum(r['state'] == 'open' for r in rs)}），"
        f"可能阻塞写作 {sum(r['blocking'] for r in rs)} 个；"
        f"版本：{', '.join(by('version')) or '—'}；平台：{', '.join(by('platform')) or '—'}。"
    )
    return "\n".join([
        START,
        "## Beta 反馈汇总（自动生成）",
        "",
        summary,
        "",
        table(rs),
        "",
        "\"初判\"只是关键词提示（崩溃、丢失内容、无法输入/保存/打开/启动）；分诊结论记在上方的手写表与 PROGRESS。",
        END,
    ])


def write(rs, path=REPORTS):
    text = open(path, encoding="utf-8").read()
    new = section(rs)
    if START in text and END in text:
        a = text.index(START)
        b = text.index(END) + len(END)
        text = text[:a] + new + text[b:]
    else:
        text = text.rstrip("\n") + "\n\n" + new + "\n"
    open(path, "w", encoding="utf-8").write(text)


SAMPLE = """### Version / 版本

1.0.0-beta.1

### Platform / 平台

Windows x64

### Package / 安装方式

MSI

### Graphics: the `graphics:` line of inkra.log / 日志中的 `graphics:` 行

20261015 INFO  inkra: graphics: backends Backends(DX12) (default); 2 adapter(s) after 120.3 ms: Intel(R) UHD (IntegratedGpu, Dx12); using Intel(R) UHD

### Steps / 重现步骤

1. Open a long file
2. Type in a table — the app crashes

### Expected and actual / 期望与实际

_No response_

### Minimal .md and inkra.log / 最小 .md 文件与日志

[inkra.log](https://github.com/user-attachments/files/123/inkra.log)
"""


def self_test():
    import tempfile
    f = parse_body(SAMPLE)
    assert f["version"] == "1.0.0-beta.1", f
    assert f["platform"] == "Windows x64" and f["package"] == "MSI", f
    assert f["graphics"].startswith("graphics: backends Backends(DX12)"), f
    assert "expected" not in f, "_No response_ is empty"
    assert attachments(SAMPLE) == ["https://github.com/user-attachments/files/123/inkra.log"]
    zh = "### Version / 版本\n\nInkra 1.0.0-beta.2（关于对话框）\n\n### Steps / 重现步骤\n\n保存后内容丢失\n"
    g = parse_body(zh)
    assert g["version"] == "1.0.0-beta.2", g
    issues = [
        {"number": 2, "title": "Typing in tables", "state": "open", "labels": [{"name": "bug"}], "body": SAMPLE},
        {"number": 3, "title": "保存后内容丢失", "state": "open", "labels": [{"name": "bug"}], "body": zh},
        {"number": 4, "title": "Tabs please", "state": "closed", "labels": [{"name": "enhancement"}], "body": "### Problem\n\ncrash course"},
    ]
    rs = rows(issues)
    assert [r["blocking"] for r in rs] == [True, True, False], rs
    with tempfile.TemporaryDirectory() as d:
        p = os.path.join(d, "r.md")
        open(p, "w", encoding="utf-8").write("# Reports\n\nhand-written\n")
        write(rs, p)
        write(rs[:1], p)  # rewriting replaces the section, keeps the rest
        t = open(p, encoding="utf-8").read()
        assert t.count(START) == 1 and "hand-written" in t and "#2" in t and "#3" not in t, t
    assert "暂无 issue" in table([])
    print("triage self-test: OK")


def main(argv):
    if "--self-test" in argv:
        self_test()
        return 0
    token = os.environ.get("GH_TOKEN") or os.environ.get("GITHUB_TOKEN")
    if "--input" in argv:
        issues = json.load(open(argv[argv.index("--input") + 1], encoding="utf-8"))
        issues = [i for i in issues if "pull_request" not in i]
    else:
        try:
            issues = fetch_issues(token)
        except urllib.error.HTTPError as e:
            print(f"GitHub API: {e} (anonymous limit is 60 requests per hour; set GH_TOKEN)", file=sys.stderr)
            return 2
    rs = rows(issues, token, "--fetch-logs" in argv)
    if "--dry-run" in argv:
        print(section(rs))
    else:
        write(rs)
        print(f"{REPORTS}: {len(rs)} issue(s)")
    for r in rs:
        if r["blocking"] and r["state"] == "open":
            print(f"may block writing: #{r['number']} {r['title']}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
