#!/usr/bin/env python3
"""Generates crates/inkra-markdown/src/emoji_table.rs from the GitHub gemoji
database (MIT, crates/inkra-markdown/data/gemoji.json). Run after updating it."""
import json, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
data = json.loads((root / "crates/inkra-markdown/data/gemoji.json").read_text())
pairs = {}
for e in data:
    if "emoji" not in e:
        continue
    for a in e["aliases"]:
        pairs.setdefault(a, e["emoji"])
lines = ["//! Generated by tools/gen_emoji.py from GitHub gemoji (MIT). Do not edit.", "",
         "/// `(shortcode, emoji)` sorted by shortcode.", "pub const EMOJI: &[(&str, &str)] = &["]
for k in sorted(pairs):
    v = pairs[k].replace("\\", "\\\\").replace('"', '\\"')
    lines.append(f'    ("{k}", "{v}"),')
lines.append("];")
(root / "crates/inkra-markdown/src/emoji_table.rs").write_text("\n".join(lines) + "\n")
print(len(pairs), "shortcodes")
