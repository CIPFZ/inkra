//! Generated documentation: `docs/commands.md`, `docs/preferences.md`,
//! `docs/keybindings.md`.

use std::collections::BTreeSet;
use std::fmt::Write;

use inkra_engine::command::title_key;
use inkra_engine::keymap::{Keymap, Os, When};
use inkra_engine::menu::{self, MenuItem};
use inkra_engine::prefs::{PREFS, PrefKind};
use inkra_i18n::I18n;

const HEADER: &str = "<!-- Generated by `cargo xtask {}`. Do not edit by hand. -->\n\n";

fn header(task: &str) -> String {
    HEADER.replace("{}", task)
}

fn esc(s: &str) -> String {
    s.replace('|', "\\|")
}

fn shortcut(km: &Keymap, id: &str, os: Os) -> String {
    let chords: Vec<String> = km
        .bindings()
        .iter()
        .filter(|b| b.command == id)
        .map(|b| {
            let mut s = format!("`{}`", esc(&b.chord.label(os)));
            match b.when {
                When::InTable => s.push_str(" (in table)"),
                When::NotInTable => s.push_str(" (outside tables)"),
                When::Always => {}
            }
            s
        })
        .collect();
    chords.join(", ")
}

/// `docs/commands.md`.
pub fn commands() -> String {
    let registry = inkra_engine::builtin_registry();
    let en = I18n::new("en-US");
    let zh = I18n::new("zh-CN");
    let km = Keymap::defaults(Os::Windows);
    let kmac = Keymap::defaults(Os::Mac);
    let mut out = header("commands");
    out.push_str("# Inkra commands\n\n");
    out.push_str(
        "Every user action is a command (SPEC AD-3, CM-001). Menus, shortcuts, toolbars, \
         context menus, the CLI (`inkra-cli run --cmd <id>`) and the control channel all \
         invoke commands by id. This file is the interface contract for automation and AI \
         agents.\n\n",
    );
    let _ = writeln!(out, "Registered commands: **{}**\n", registry.len());
    let mut current = None;
    for cmd in registry.iter() {
        let s = cmd.spec();
        if current != Some(s.category) {
            current = Some(s.category);
            let _ = writeln!(out, "\n## {}\n", s.category.name());
            out.push_str("| Id | Title | 中文 | Shortcut (Win/Linux) | Shortcut (macOS) | Params | Req | Description |\n");
            out.push_str("|---|---|---|---|---|---|---|---|\n");
        }
        let params = s
            .params
            .map(|p| format!("`{}`", esc(p)))
            .unwrap_or_else(|| "—".into());
        let _ = writeln!(
            out,
            "| `{}` | {} | {} | {} | {} | {} | {} | {} |",
            s.id,
            esc(&en.tr(&s.title_key())),
            esc(&zh.tr(&s.title_key())),
            shortcut(&km, s.id, Os::Windows),
            shortcut(&kmac, s.id, Os::Mac),
            params,
            s.req,
            esc(s.doc),
        );
    }
    let mut planned = BTreeSet::new();
    menu::for_each_command(|item| {
        if let MenuItem::Command { id, .. } = item
            && !registry.contains(id)
        {
            planned.insert(*id);
        }
    });
    for b in km.bindings() {
        if !registry.contains(&b.command) {
            planned.insert(b.command.as_str());
        }
    }
    if !planned.is_empty() {
        out.push_str("\n## Reserved ids (in menus or key map, not implemented yet)\n\n");
        out.push_str("These appear greyed out in menus.\n\n");
        for id in planned {
            let _ = writeln!(out, "- `{id}` — {}", esc(&en.tr(&title_key(id))));
        }
    }
    out
}

fn kind(k: PrefKind) -> String {
    match k {
        PrefKind::Bool => "bool".into(),
        PrefKind::Number => "number".into(),
        PrefKind::String => "string".into(),
        PrefKind::StringList => "string[]".into(),
        PrefKind::Enum(opts) => opts
            .iter()
            .map(|o| format!("`{o}`"))
            .collect::<Vec<_>>()
            .join(" / "),
    }
}

/// `docs/preferences.md`.
pub fn preferences() -> String {
    let mut out = header("prefs");
    out.push_str("# Inkra preferences\n\n");
    out.push_str(
        "Stored in `conf.user.json` (PR-001): Windows `%APPDATA%\\Inkra\\`, macOS \
         `~/Library/Application Support/Inkra/`, Linux `$XDG_CONFIG_HOME/inkra/`. Flat JSON \
         object with dotted keys; unknown keys are preserved; writes are atomic; a corrupt \
         file is backed up as `conf.user.json.bak-<timestamp>` (PR-003).\n\n",
    );
    out.push_str("| Key | Type | Default | Req | Description |\n|---|---|---|---|---|\n");
    for p in PREFS {
        let _ = writeln!(
            out,
            "| `{}` | {} | `{}` | {} | {} |",
            p.key,
            esc(&kind(p.kind)),
            esc(p.default),
            p.req,
            esc(p.doc)
        );
    }
    out
}

/// `docs/keybindings.md`.
pub fn keybindings() -> String {
    let en = I18n::new("en-US");
    let win = Keymap::defaults(Os::Windows);
    let mac = Keymap::defaults(Os::Mac);
    let mut ids: Vec<&str> = Vec::new();
    for b in win.bindings().iter().chain(mac.bindings()) {
        if !ids.contains(&b.command.as_str()) {
            ids.push(&b.command);
        }
    }
    let mut out = header("keybindings");
    out.push_str("# Inkra default key bindings\n\n");
    out.push_str(
        "SPEC 10.2 (UI-010). `Ctrl` is `Cmd` (⌘) on macOS. User overrides go to \
         `<config>/keybindings.json` (UI-020).\n\n",
    );
    out.push_str("| Command | Title | Windows / Linux | macOS |\n|---|---|---|---|\n");
    for id in ids {
        let _ = writeln!(
            out,
            "| `{id}` | {} | {} | {} |",
            esc(&en.tr(&title_key(id))),
            shortcut(&win, id, Os::Windows),
            shortcut(&mac, id, Os::Mac)
        );
    }
    out
}
